#!/usr/bin/env bash
# Writes secrets/prometheus-web.yml (bcrypt hash of PROMETHEUS_PASSWORD) for Prometheus basic auth.
# Adds PROMETHEUS_USER/PROMETHEUS_PASSWORD to .env if missing. Re-run after changing the password.
set -euo pipefail
cd "$(dirname "$0")/.."
[[ -f .env ]] || { echo "run scripts/gen-secrets.sh first" >&2; exit 1; }
grep -q '^PROMETHEUS_USER=' .env || echo "PROMETHEUS_USER=prometheus" >> .env
grep -q '^PROMETHEUS_PASSWORD=' .env || echo "PROMETHEUS_PASSWORD=$(openssl rand -base64 36 | tr -d '\n/+=' | cut -c1-32)" >> .env
set -a; source .env; set +a
if python3 -c "import bcrypt" 2>/dev/null; then
  hash=$(PW="$PROMETHEUS_PASSWORD" python3 -c "import bcrypt,os; print(bcrypt.hashpw(os.environ['PW'].encode(), bcrypt.gensalt(12)).decode())")
else
  hash=$(docker run --rm httpd:2.4-alpine htpasswd -nbBC 12 x "$PROMETHEUS_PASSWORD" | cut -d: -f2)
fi
mkdir -p secrets
umask 022
cat > secrets/prometheus-web.yml <<YML
# Prometheus web config: basic auth (generated by scripts/gen-prometheus-auth.sh — do not commit)
basic_auth_users:
  ${PROMETHEUS_USER}: ${hash}
YML
echo "wrote secrets/prometheus-web.yml (user ${PROMETHEUS_USER})"
